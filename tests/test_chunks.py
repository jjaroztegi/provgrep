from pathlib import PurePosixPath

from provgrep.chunks import MAX_LINES, kind, language_of, units


def _units(name: str, text: str) -> list[tuple[str, int, int]]:
    language = language_of(PurePosixPath(name), cpp=True)
    assert language is not None
    return [(u.symbol, u.start, u.end) for u in units(text, language)]


def test_cpp_templates_out_of_line_methods_and_classes() -> None:
    cpp = """// Copyright 2020 A
#include <X11/extensions/Xrender.h>

namespace rfb {
// Make a picture
template <typename T>
static T *Surface::draw(int x)
{
  x++;
  return 0;
}
class B {
  int f() const {
    int y = 1;
    return y;
  }
};
}
"""
    assert _units("a.cxx", cpp) == [("rfb.Surface::draw", 5, 11), ("rfb.B.f", 13, 16)]


def test_javascript_functions_and_the_file_header() -> None:
    js = """/**
 * Header of the file, not of the function.
 */
export const debounce = (fn, ms) => {
  let t;
  return t;
};
Foo.prototype.bar = function () {
  bar();
  return 1;
};
class K {
  // Does m.
  m() {
    m();
    return 3;
  }
}
"""
    assert _units("b.js", js) == [("debounce", 4, 7), ("Foo.prototype.bar", 8, 11), ("K.m", 13, 17)]


def test_go_receivers_rust_impls_and_test_modules() -> None:
    go = "package p\n\n// Handle does x.\nfunc (s *Server[T]) Handle() {\n\tx := 1\n\t_ = x\n}\n"
    assert _units("c.go", go) == [("Server.Handle", 3, 7)]
    rust = """use std::io;
/// Does g.
#[inline]
fn g() {
    a();
    1
}
impl<T> Foo<T> {
    fn h(&self) {
        b();
        2
    }
}
mod tests {
    fn t() {
        c();
        3
    }
}
"""
    assert _units("d.rs", rust) == [("g", 2, 7), ("Foo.h", 9, 12)]


def test_python_docstrings_decorators_and_nesting() -> None:
    py = '''import os


@cache
def parse_rtp_header(data):
    """Parse an RTP header."""
    def inner():
        return 1
    # version is 2 bits
    return data[0] >> 6
'''
    (unit,) = units(py, "python")
    assert (unit.symbol, unit.start, unit.end) == ("parse_rtp_header", 4, 10)
    assert unit.doc == "Parse an RTP header.\n# version is 2 bits"
    long_wrapper = "def wrapper():\n" + "    x = 1\n" * MAX_LINES + "    def f():\n        x = 2\n"
    long_wrapper += "        return x\n"
    assert [u.symbol for u in units(long_wrapper, "python")] == ["f"]


def test_copies_at_another_indentation_have_the_same_hash() -> None:
    top = units("def f(a):\n    b = a\n\n    return b\n", "python")
    method = units("class C:\n    def f(a):\n        b = a\n        return b  \n", "python")
    assert top[0].hash == method[0].hash


def test_kind() -> None:
    def k(path: str, text: str = "", language: str = "python") -> str:
        return kind(PurePosixPath(path), text, language)

    assert k("tests/util.py") == "test"
    assert k("pkg/test_util.py") == "test"
    assert k("src/a.test.ts", language="typescript") == "test"
    assert k("server_test.go", language="go") == "test"
    assert k("api_pb2.py") == "generated"
    assert k("x.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n", "go") == "generated"
    assert k("app.js", "var a=1;" * 2000, "javascript") == "generated"
    assert k("src/_vendor/six.py") == "vendored"
    assert k("src/util.py", '"""Returns the token generated by the server."""\n') == "code"


def test_header_language_follows_the_tree() -> None:
    assert language_of(PurePosixPath("x.h"), cpp=False) == "c"
    assert language_of(PurePosixPath("x.h"), cpp=True) == "cpp"
    assert language_of(PurePosixPath("README.md"), cpp=True) is None


def test_one_statement_bodies_are_not_units() -> None:
    java = "class A {\n  int getX() {\n    return x;\n  }\n"
    java += "  int sum() {\n    int s = a;\n    s += b;\n    return s;\n  }\n}\n"
    assert _units("A.java", java) == [("A.sum", 5, 9)]
    assert _units("f.py", "def f():\n    '''Doc.'''\n    return 1\n") == [("f", 1, 3)]


def test_emails_leave_comments_not_code() -> None:
    java = """class A {
  /** Sums. @author Jane Doe <jane@example.org> */
  int sum() {
    String to = "ops@example.org";  // or ops [at] example (dot) org
    return send(to);
  }
}
"""
    (unit,) = units(java, "java")
    assert "jane@" not in unit.code
    assert "@author Jane Doe */" in unit.code
    assert '"ops@example.org"' in unit.code  # a string literal is code
    assert "[at]" not in unit.code
    assert (unit.start, unit.end) == (2, 6)


def test_declarations_without_a_body_are_not_units() -> None:
    java = """interface I {
  private static native void render(int dst, byte op,
                                    short red, short green,
                                    short blue, short alpha);
}
"""
    assert units(java, "java") == []
    go = "package p\n\n// Implemented in assembly.\nfunc add(\n\tx int,\n\ty int,\n) int\n"
    assert units(go, "go") == []
